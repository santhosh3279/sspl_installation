#!/bin/bash
# Install WireGuard on the host, so the ERP containers can reach the CUPS print
# servers in the shops. This server is the hub; print servers dial in.
#
# Add print servers afterwards: sites/wireguard.sh add <name>  (or the panel).
# Idempotent: re-run to change WG_ENDPOINT / WG_PORT or to repair.
#
# Env (empty keeps what is configured):
#   WG_ENDPOINT   public IP or DNS name the print servers dial (required once)
#   WG_PORT       UDP port (default 51820)
#   WG_SUBNET     a /24 (default 10.99.0.0/24); fixed once peers exist
#   SSPL_CONF     default /opt/sspl-erp/sspl-mt.conf
#
# SECURITY: private keys stay in /etc/wireguard (0600). Do not add 'set -x'.
set -euo pipefail

export SSPL_CONF="${SSPL_CONF:-/opt/sspl-erp/sspl-mt.conf}"
[ "$(id -u)" -eq 0 ] || { echo "❌ Run as root (sudo)." >&2; exit 1; }
[ -f "$SSPL_CONF" ] || { echo "❌ $SSPL_CONF is missing — install the stack first." >&2; exit 1; }
_EP="${WG_ENDPOINT:-}"; _PORT="${WG_PORT:-}"; _NET="${WG_SUBNET:-}"
HERE="$(cd "$(dirname "$0")/.." && pwd)"
source "$HERE/lib/common.sh"
take_lock

step "Configuration"
OLD_PORT="$WG_PORT"; OLD_NET="$WG_SUBNET"
WG_ENDPOINT="${_EP:-$WG_ENDPOINT}"; WG_PORT="${_PORT:-$WG_PORT}"; WG_SUBNET="${_NET:-$WG_SUBNET}"
[[ "$WG_ENDPOINT" =~ $WG_ENDPOINT_RE ]] || err "WG_ENDPOINT must be the public IP or DNS name of this server"
valid_port "$WG_PORT" || err "WG_PORT must be 1-65535"
[[ "$WG_SUBNET" =~ $WG_SUBNET_RE ]] || err "WG_SUBNET must be a private /24, e.g. 10.99.0.0/24"
if [ "$WG_SUBNET" != "$OLD_NET" ] && [ -n "$(wg_peer_lines)" ]; then
    err "WG_SUBNET cannot change while print servers exist (they use addresses in $OLD_NET)"
fi
# The subnet must not swallow a network this server already uses.
ip -4 -o addr show | awk -v i="$WG_IFACE" '$2 != i {print $4}' | python3 -c '
import ipaddress, sys
n = ipaddress.ip_network(sys.argv[1])
if not n.is_private: sys.exit("not a private network")
for l in sys.stdin.read().split():
    if n.overlaps(ipaddress.ip_interface(l).network): sys.exit(f"overlaps {l}")
' "$WG_SUBNET" || err "WG_SUBNET $WG_SUBNET cannot be used — choose another /24"
if [ ! -d "/sys/class/net/$WG_IFACE" ] || [ "$WG_PORT" != "$OLD_PORT" ]; then
    [ -z "$(ss -lunH "sport = :$WG_PORT")" ] || err "UDP port $WG_PORT is already in use"
fi

step "Packages"
if ! command -v wg-quick >/dev/null || ! command -v iptables >/dev/null; then
    apt-get update -qq
    DEBIAN_FRONTEND=noninteractive apt-get install -y wireguard-tools iptables
fi
ok "wireguard-tools"

set_conf() {   # KEY VALUE
    local tmp
    tmp=$(mktemp "$SSPL_CONF.XXXXXX")
    awk -v k="$1" -v v="$2" '$0 ~ "^"k"=" {print k"=\""v"\""; d=1; next} {print} END{if(!d) print k"=\""v"\""}' \
        "$SSPL_CONF" > "$tmp"
    chmod --reference="$SSPL_CONF" "$tmp"; mv -f "$tmp" "$SSPL_CONF"
}
grep -q '^WG_PORT=' "$SSPL_CONF" || printf '\n# WireGuard to the print servers (sites/wireguard.sh)\n' >> "$SSPL_CONF"
set_conf WG_PORT "$WG_PORT"
set_conf WG_SUBNET "$WG_SUBNET"
set_conf WG_ENDPOINT "$WG_ENDPOINT"

step "Keys and firewall"
umask 077
mkdir -p "$WG_DIR/sspl-peers"
chmod 700 "$WG_DIR" "$WG_DIR/sspl-peers"
[ -s "$WG_DIR/sspl-wg.key" ] || wg genkey > "$WG_DIR/sspl-wg.key"

# One direction only: host and containers → print servers.
cat > "$WG_DIR/sspl-wg-fw.sh" <<'FW'
#!/bin/bash
# Generated by install-wireguard.sh. Usage: sspl-wg-fw.sh up|down <iface>
#   in       replies and ping only: a print server cannot reach this host
#   forward  Docker bridges → tunnel, plus replies; nothing else (no
#            peer-to-peer, no LAN → tunnel, no peer → containers)
#   nat      containers leave as the hub address, the only one peers accept
#   mss      large print jobs fit the smaller tunnel MTU
set -u
ACT="$1"; I="$2"
ipt() { iptables -w "$@"; }
down() {
    ipt -D INPUT -i "$I" -j SSPL-WG-IN
    ipt -D FORWARD -i "$I" -j SSPL-WG-FWD
    ipt -D FORWARD -o "$I" -j SSPL-WG-FWD
    ipt -t nat -D POSTROUTING -o "$I" -j MASQUERADE
    ipt -t mangle -D FORWARD -o "$I" -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu
    for c in SSPL-WG-IN SSPL-WG-FWD; do ipt -F "$c"; ipt -X "$c"; done
}
down >/dev/null 2>&1
[ "$ACT" = up ] || exit 0
set -e
ipt -N SSPL-WG-IN
ipt -A SSPL-WG-IN -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT
ipt -A SSPL-WG-IN -p icmp --icmp-type echo-request -j ACCEPT
ipt -A SSPL-WG-IN -j DROP
ipt -N SSPL-WG-FWD
ipt -A SSPL-WG-FWD -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT
ipt -A SSPL-WG-FWD -i br-+ -o "$I" -p tcp -j ACCEPT
ipt -A SSPL-WG-FWD -j DROP
ipt -I INPUT 1 -i "$I" -j SSPL-WG-IN
ipt -I FORWARD 1 -i "$I" -j SSPL-WG-FWD
ipt -I FORWARD 1 -o "$I" -j SSPL-WG-FWD
ipt -t nat -I POSTROUTING 1 -o "$I" -j MASQUERADE
ipt -t mangle -A FORWARD -o "$I" -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu
FW
chmod 700 "$WG_DIR/sspl-wg-fw.sh"
if command -v ufw >/dev/null && ufw status 2>/dev/null | grep '^Status: active' >/dev/null; then
    [ "$OLD_PORT" = "$WG_PORT" ] || ufw delete allow "$OLD_PORT/udp" >/dev/null 2>&1 || true
    ufw allow "$WG_PORT/udp" >/dev/null
    ok "ufw: $WG_PORT/udp open"
fi

step "Interface $WG_IFACE"
tmp=$(mktemp "$(wg_conf_file).XXXXXX")
write_wg_unit || { rm -f "$tmp"; err "could not write the systemd drop-in"; }
render_wg_conf > "$tmp" || { rm -f "$tmp"; err "could not render the WireGuard config"; }
mv -f "$tmp" "$(wg_conf_file)"
systemctl enable "wg-quick@$WG_IFACE" >/dev/null 2>&1
systemctl restart "wg-quick@$WG_IFACE" || err "wg-quick@$WG_IFACE did not start — journalctl -u wg-quick@$WG_IFACE"
wg show "$WG_IFACE" listen-port >/dev/null || err "$WG_IFACE is not up"

echo ""
echo "✅ WireGuard is up: $(wg_hub_ip), UDP $WG_PORT, print servers dial $WG_ENDPOINT:$WG_PORT"
echo "   Open UDP $WG_PORT in the cloud firewall / forward it on the router."
echo "   Next: $TOOLS_DIR/sites/wireguard.sh add <name>"
